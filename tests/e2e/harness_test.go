// binPath returns the newscache binary, or skips the test.
func binPath(t *testing.T) string {
	t.Helper()
	p := os.Getenv("NEWSCACHE_BIN")
	if p == "" {
		p = "../../src/newscache"
	}
	abs, err := filepath.Abs(p)
	if err != nil {
		t.Fatal(err)
	}
	if st, err := os.Stat(abs); err != nil || st.IsDir() {
		t.Skipf("newscache binary not found at %s (set NEWSCACHE_BIN)", abs)
	}
	return abs
}

// env is one NewsCache instance with its own spool, config and upstream.
type env struct {
	t          *testing.T
	Bin        string
	Dir        string // temp dir holding everything
	Conf       string // path of newscache.conf
	Spool      string
	LogDir     string
	Upstream   *fakeserver.Server
	Store      *fakeserver.Store
	Listen     string // 127.0.0.1:port for standalone mode
	ListenTo   string // ListenTo value if not Listen, e.g. "DEFAULT:port"
	NoListenTo bool   // write no ListenTo line (for CachePort)

	// Settings written into newscache.conf; change before Start*.
	MaxConnections int
	ClientTimeout  int
	ServerOptions  string // Options line of the upstream server, "" = default
	ServerHost     string // upstream host for NewsCache, "" = the fake upstream
	ServerPort     string // upstream port, "" = the fake upstream's
	ServerLines    string // extra lines in the upstream's Server block
	// A zero group timeout still needs the next clock second to expire.
	GroupTimeout   int
	ExtraServers   string // more Server blocks after the upstream's, in NewsServerList
	Extra          string // extra lines at the end of the config
	AccessList     string // the whole AccessList block
	afterPortCheck func() // test hook: run once between the port check and daemon start
}

// newEnv creates the temp dir, the fake upstream (empty Store; add groups and
// articles through e.Store) and the default settings.
func newEnv(t *testing.T) *env {
	t.Helper()
	e := &env{
		t:              t,
		Bin:            binPath(t),
		Dir:            t.TempDir(),
		Store:          fakeserver.NewStore(),
		MaxConnections: 8,
		ClientTimeout:  60,
		GroupTimeout:   0,
		AccessList:     DefaultAccessList,
	}
	e.Spool = filepath.Join(e.Dir, "spool")
	e.LogDir = filepath.Join(e.Dir, "log")
	for _, d := range []string{e.Spool, e.LogDir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	e.Upstream = fakeserver.New(t, fakeserver.Options{Store: e.Store})
	e.Listen = freeAddr(t)
	t.Cleanup(func() {
		if t.Failed() {
			t.Logf("upstream received %d lines:\n  %s", len(e.Upstream.Lines()),
				strings.Join(e.Upstream.Lines(), "\n  "))
		}
	})
	return e
}

// freeAddr returns a 127.0.0.1 address with a port that was free a moment ago.
func freeAddr(t *testing.T) string {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer l.Close()
	return l.Addr().String()
}

// DefaultAccessList allows inetd sessions (client name "stdin") and
// 127.0.0.0/8 to read and post without authentication.
const DefaultAccessList = `AccessList {
  Client stdin {
    allow read post
    List *
    Read *
    PostTo *
    Authentication none
  }
  Client 127.0.0.0/8 {
    allow read post
    List *
    Read *
    PostTo *
    Authentication none
  }
  Default {
    allow none
  }
}`

// accessEntry returns an AccessList with one Client entry for pattern that
// allows everything, and a Default entry that denies everything.
func accessEntry(pattern string) string {
	return `AccessList {
  Client ` + pattern + ` {
    allow read post
    List *
    Read *
    PostTo *
    Authentication none
  }
  Default {
    allow none
  }
}`
}

