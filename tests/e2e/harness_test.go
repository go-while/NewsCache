// listenTo is the ListenTo value of the config, "" for none.
func listenTo(e *env) string {
	if e.NoListenTo {
		return ""
	}
	return firstNonEmpty(e.ListenTo, e.Listen)
}

// extraKeys identifies top-level directives in Extra, so their template
// defaults are omitted rather than relying on duplicate-key precedence.
func extraKeys(extra string) map[string]bool {
	keys := make(map[string]bool)
	depth := 0
	for _, line := range strings.Split(extra, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if depth == 0 {
			if fields := strings.Fields(line); len(fields) > 0 {
				keys[strings.ToLower(fields[0])] = true
			}
		}
		depth += strings.Count(line, "{") - strings.Count(line, "}")
	}
	return keys
}

func TestHarnessExtraOverridesDefaults(t *testing.T) {
	e := newEnv(t)
	e.Extra = "Hostname override.test\nPidFile " + filepath.Join(e.Dir, "other.pid") + "\n"
	e.writeConf()
	data, err := os.ReadFile(e.Conf)
	if err != nil {
		t.Fatal(err)
	}
	for _, check := range []struct{ key, value string }{
		{"Hostname", "override.test"},
		{"PidFile", filepath.Join(e.Dir, "other.pid")},
	} {
		var values []string
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(line)
			if len(fields) >= 2 && strings.EqualFold(fields[0], check.key) {
				values = append(values, fields[1])
			}
		}
		if len(values) != 1 || values[0] != check.value {
			t.Errorf("%s values %q, want only %q", check.key, values, check.value)
		}
	}
}

// writeConf writes newscache.conf from the current settings.
func (e *env) writeConf() {
	e.t.Helper()
	u, err := user.Current()
	if err != nil {
		e.t.Fatal(err)
	}
	g, err := user.LookupGroupId(u.Gid)
	if err != nil {
		e.t.Fatal(err)
	}
	data := map[string]any{
		"Listen":         listenTo(e),
		"Dir":            e.Dir,
		"User":           u.Username,
		"Group":          g.Name,
		"Spool":          e.Spool,
		"LogDir":         e.LogDir,
		"ClientTimeout":  e.ClientTimeout,
		"MaxConnections": e.MaxConnections,
		"UpHost":         firstNonEmpty(e.ServerHost, e.Upstream.Host()),
		"UpPort":         firstNonEmpty(e.ServerPort, fmt.Sprint(e.Upstream.Port())),
		"ServerLines":    e.ServerLines,
		"ExtraServers":   e.ExtraServers,
		"GroupTimeout":   e.GroupTimeout,
		"ServerOptions":  e.ServerOptions,
		"Extra":          e.Extra,
		"ExtraKeys":      extraKeys(e.Extra),
		"AccessList":     e.AccessList,
	}
	var b strings.Builder
	if err := confTmpl.Execute(&b, data); err != nil {
		e.t.Fatal(err)
	}
	e.Conf = filepath.Join(e.Dir, "newscache.conf")
	if err := os.WriteFile(e.Conf, []byte(b.String()), 0o644); err != nil {
		e.t.Fatal(err)
	}
}

func (e *env) procOpts(args ...string) proc.Options {
	return proc.Options{
		Path: e.Bin,
		Args: append([]string{"-c", e.Conf}, args...),
		Dir:  e.Dir,
		Logs: []string{filepath.Join(e.LogDir, "newscache.log")},
	}
}

// session starts newscache in inetd mode (-i) for one client session and
// returns the strict client after reading the greeting.
func (e *env) session() *client.Conn {
	e.t.Helper()
	_, c := e.sessionProcess()
	return c
}

// sessionProcess also returns the inetd process so tests can wait for log
// flushing and other exit-time work instead of sleeping after QUIT.
func (e *env) sessionProcess() (*proc.Process, *client.Conn) {
	e.t.Helper()
	e.writeConf()
	p := proc.StartStdio(e.t, e.procOpts("-i"))
	c := client.New(e.t, p.Conn())
	if _, err := c.ReadGreeting(); err != nil {
		e.t.Fatalf("greeting: %v", err)
	}
	return p, c
}

func quitSession(t *testing.T, p *proc.Process, c *client.Conn) {
	t.Helper()
	if code, line := c.Cmd("QUIT"); code != 205 {
		t.Fatalf("QUIT: %q, want 205", line)
	}
	if err := p.Wait(); err != nil {
		t.Fatalf("session exit after QUIT: %v", err)
	}
}

// standalone starts newscache as a daemon in the foreground (-n) listening on
// e.Listen. A port that was free when chosen can be taken before bind; retry
// a failed bind only for the default loopback listener.
func (e *env) standalone() *proc.Process {
	e.t.Helper()
	const attempts = 3
	for attempt := 0; attempt < attempts; attempt++ {
		automatic := !e.NoListenTo && e.ListenTo == "" && !extraKeys(e.Extra)["listento"]
		if automatic {
			// Do not mistake a different server's greeting for our daemon's
			// when the previously selected address is already occupied.
			probe, err := net.Listen("tcp", e.Listen)
			if err == nil {
				_ = probe.Close()
			} else if errors.Is(err, syscall.EADDRINUSE) && attempt+1 < attempts {
				e.Listen = freeAddr(e.t)
				continue
			}
		}
		if e.afterPortCheck != nil {
			hook := e.afterPortCheck
			e.afterPortCheck = nil
			hook()
		}
		e.writeConf()
		// StartStdio returns immediately, unlike StartTCP's fatal-on-exit
		// readiness wait. The foreground daemon does not read stdin. Drain
		// stdout so it cannot block if it writes more than a pipe can hold.
		p := proc.StartStdio(e.t, e.procOpts("-n"))
		_ = p.Conn().SetReadDeadline(time.Now().Add(24 * time.Hour))
		go func() { _, _ = io.Copy(io.Discard, p.Conn()) }()
		deadline := time.Now().Add(testkit.Deadline())
		for time.Now().Before(deadline) {
			select {
			case <-p.Done():
				err := p.Wait()
				output := p.Stderr()
				retry := automatic &&
					strings.Contains(output, "can't listen on ListenTo "+e.Listen+":")
				if retry && attempt+1 < attempts {
					e.Listen = freeAddr(e.t)
					break
				}
				e.t.Fatalf("daemon exited before %s was ready: %v\n%s", e.Listen, err, output)
			default:
				conn, err := net.DialTimeout("tcp", e.Listen, 250*time.Millisecond)
				if err == nil {
					_ = conn.SetDeadline(time.Now().Add(250 * time.Millisecond))
					_, err = bufio.NewReader(conn).ReadString('\n')
					if err == nil {
						_, _ = io.WriteString(conn, "QUIT\r\n")
					}
					_ = conn.Close()
					if err == nil {
						select {
						case <-p.Done():
							continue
						default:
							return p
						}
					}
				}
				time.Sleep(20 * time.Millisecond)
				continue
			}
			break // a bind collision: retry with a fresh address
		}
		select {
		case <-p.Done():
			// The failed attempt was reaped by proc; start the next one.
		default:
			p.Stop()
			e.t.Fatalf("daemon not ready on %s within %s: %s", e.Listen, testkit.Deadline(), p.Stderr())
		}
	}
	e.t.Fatal("daemon could not acquire a loopback port after retries")
	return nil
}

func TestStandaloneRetriesBusyAddress(t *testing.T) {
	occupied, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer occupied.Close()
	go func() {
		for {
			conn, err := occupied.Accept()
			if err != nil {
				return
			}
			_, _ = io.WriteString(conn, "200 another server\r\n")
			_ = conn.Close()
		}
	}()
	e := newEnv(t)
	e.Listen = occupied.Addr().String()
	busy := e.Listen
	e.standalone()
	if e.Listen == busy {
		t.Fatalf("daemon retained occupied address %s", busy)
	}
	c := e.dial()
	if code, line := c.Cmd("DATE"); code != 111 {
		t.Errorf("DATE after retry: %q", line)
	}
}

// A port can also be taken after the preflight check and before NewsCache
// binds. Exercise the separate retry after the daemon reports that failure.
func TestStandaloneRetriesStolenAddress(t *testing.T) {
	e := newEnv(t)
	var busy string
	e.afterPortCheck = func() {
		busy = e.Listen
		occupied, err := net.Listen("tcp", busy)
		if err != nil {
			t.Fatalf("occupy port after preflight: %v", err)
		}
		t.Cleanup(func() { _ = occupied.Close() })
	}
	e.standalone()
	if busy == "" || e.Listen == busy {
		t.Fatalf("daemon did not retry stolen address %q (now %q)", busy, e.Listen)
	}
	c := e.dial()
	if code, line := c.Cmd("DATE"); code != 111 {
		t.Errorf("DATE after retry: %q", line)
	}
}

func (e *env) dial() *client.Conn {
	e.t.Helper()
	return client.Dial(e.t, e.Listen)
}

// addArticles adds n articles to a new group and returns their message-IDs.
// Each article carries an Xref header, as real servers send one.
func (e *env) addArticles(group string, n int) []string {
	return e.addArticlesXref(group, n, true)
}

func (e *env) addArticlesXref(group string, n int, xref bool) []string {
	e.Store.AddGroup(group, "test group "+group)
	ids := make([]string, 0, n)
	for i := 1; i <= n; i++ {
		id := fmt.Sprintf("<%s.%d@upstream.test>", strings.ReplaceAll(group, ".", "-"), i)
		h := []string{
			"From: poster@upstream.test",
			fmt.Sprintf("Subject: article %d in %s", i, group),
			"Newsgroups: " + group,
		}
		if xref {
			h = append(h, fmt.Sprintf("Xref: upstream.test %s:%d", group, i))
		}
		e.Store.AddArticle(group, fakeserver.Article{
			Number:    int64(i),
			MessageID: id,
			Headers:   h,
			Body:      []string{fmt.Sprintf("body of article %d", i), "second line", ".starts with a dot"},
		})
		ids = append(ids, id)
	}
	return ids
}

// knownBug marks a test that shows a known NewsCache bug. By default the test
// is skipped with the bug's ID; NEWSCACHE_KNOWN_BUGS=fail runs it as a normal
// failing test (use this when working on the fix).
func knownBug(t *testing.T, id, what string) {
	t.Helper()
	if os.Getenv("NEWSCACHE_KNOWN_BUGS") == "fail" {
		t.Logf("known bug %s: %s", id, what)
		return
	}
	t.Skipf("known bug %s: %s (NEWSCACHE_KNOWN_BUGS=fail to run)", id, what)
}

var logModes = struct {
	sync.Mutex
	byBin map[string]string
}{byBin: make(map[string]string)}

// logMode determines the build mode from the actual binary, independently of
// whether a particular test's log exists. -o needs no configuration file.
// Cache successful queries: some tests poll logFile every 50 milliseconds.
func logMode(bin string) (string, error) {
	logModes.Lock()
	defer logModes.Unlock()
	if mode, ok := logModes.byBin[bin]; ok {
		return mode, nil
	}
	b, err := exec.Command(bin, "-o").Output()
	if err != nil {
		return "", fmt.Errorf("cannot determine logging mode from %s -o: %w", bin, err)
	}
	for _, option := range strings.Fields(string(b)) {
		if option == "--with-syslog" {
			logModes.byBin[bin] = "syslog"
			return "syslog", nil
		}
	}
	logModes.byBin[bin] = "file"
	return "file", nil
}

func readLogFile(mode, path string) (string, bool, error) {
	if mode == "syslog" {
		return "", true, nil
	}
	if mode != "file" {
		return "", false, fmt.Errorf("invalid logging mode %q", mode)
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return "", false, fmt.Errorf("file-log build: cannot read %s: %w", path, err)
	}
	return string(b), false, nil
}

// logFile returns the NewsCache log, or skips only for a syslog build.
func (e *env) logFile() string {
	e.t.Helper()
	mode, err := logMode(e.Bin)
	if err != nil {
		e.t.Fatal(err)
	}
	log, skip, err := readLogFile(mode, filepath.Join(e.LogDir, "newscache.log"))
	if err != nil {
		e.t.Fatal(err)
	}
	if skip {
		e.t.Skip("binary built with syslog (configure --without-syslog to test logging)")
	}
	return log
}

// waitLog waits for a positive log marker from a standalone child/daemon.
// It is for file-log builds; logFile handles the syslog-build skip.
func (e *env) waitLog(marker string) string {
	e.t.Helper()
	deadline := time.Now().Add(5 * time.Second)
	var log string
	for {
		log = e.logFile()
		if strings.Contains(log, marker) {
			return log
		}
		if !time.Now().Before(deadline) {
			e.t.Fatalf("timed out waiting for %q in log:\n%s", marker, log)
		}
		time.Sleep(25 * time.Millisecond)
	}
}

// dialRaw connects without failing on a non-2xx greeting.
func (e *env) dialRaw() *client.Conn {
	e.t.Helper()
	c, err := client.TryDial(e.Listen, 0)
	if err != nil {
		e.t.Fatalf("dial %s: %v", e.Listen, err)
	}
	return c.WithTB(e.t)
}

// dialLenient connects with strict mode off, for replies that are known to
// break the wire format (bare LF), so the test can still check the code.
func (e *env) dialLenient() *client.Conn {
	e.t.Helper()
	nc, err := net.Dial("tcp", e.Listen)
	if err != nil {
		e.t.Fatalf("dial %s: %v", e.Listen, err)
	}
	c := client.New(e.t, nc)
	c.Strict = false
	if _, err := c.ReadGreeting(); err != nil {
		e.t.Fatalf("greeting: %v", err)
	}
	return c
}

func firstNonEmpty(a, b string) string {
	if a != "" {
		return a
	}
	return b
}
