package e2e

// Harness for NewsCache end-to-end tests: a fake upstream (nntp-testkit
// fakeserver in Store mode), a generated newscache.conf in a temp dir, and the
// real newscache binary run either inetd style (stdin/stdout) or standalone on
// a TCP port.
//
// The binary is $NEWSCACHE_BIN, default ../../src/newscache. Tests are skipped
// when it does not exist.

import (
	"fmt"
	"net"
	"os"
	"os/exec"
	"os/user"
	"path/filepath"
	"strings"
	"sync"
	"testing"
	"text/template"
	"time"

	"github.com/go-while/nntp-testkit/client"
	"github.com/go-while/nntp-testkit/fakeserver"
	"github.com/go-while/nntp-testkit/proc"
)

// binPath returns the newscache binary, or skips the test.
func binPath(t *testing.T) string {
	t.Helper()
	p := os.Getenv("NEWSCACHE_BIN")
	if p == "" {
		p = "../../src/newscache"
	}
	abs, err := filepath.Abs(p)
	if err != nil {
		t.Fatal(err)
	}
	if st, err := os.Stat(abs); err != nil || st.IsDir() {
		t.Skipf("newscache binary not found at %s (set NEWSCACHE_BIN)", abs)
	}
	return abs
}

// env is one NewsCache instance with its own spool, config and upstream.
type env struct {
	t          *testing.T
	Bin        string
	Dir        string // temp dir holding everything
	Conf       string // path of newscache.conf
	Spool      string
	LogDir     string
	Upstream   *fakeserver.Server
	Store      *fakeserver.Store
	Listen     string // 127.0.0.1:port for standalone mode
	ListenTo   string // ListenTo value if not Listen, e.g. "DEFAULT:port"
	NoListenTo bool   // write no ListenTo line (for CachePort)

	// Settings written into newscache.conf; change before Start*.
	MaxConnections int
	ClientTimeout  int
	ServerOptions  string // Options line of the upstream server, "" = default
	ServerHost     string // upstream host for NewsCache, "" = the fake upstream
	ServerPort     string // upstream port, "" = the fake upstream's
	ServerLines    string // extra lines in the upstream's Server block
	// A zero group timeout still needs the next clock second to expire.
	GroupTimeout int
	ExtraServers string // more Server blocks after the upstream's, in NewsServerList
	Extra        string // extra lines at the end of the config
	AccessList   string // the whole AccessList block
}

// newEnv creates the temp dir, the fake upstream (empty Store; add groups and
// articles through e.Store) and the default settings.
func newEnv(t *testing.T) *env {
	t.Helper()
	e := &env{
		t:              t,
		Bin:            binPath(t),
		Dir:            t.TempDir(),
		Store:          fakeserver.NewStore(),
		MaxConnections: 8,
		ClientTimeout:  60,
		GroupTimeout:   0,
		AccessList:     DefaultAccessList,
	}
	e.Spool = filepath.Join(e.Dir, "spool")
	e.LogDir = filepath.Join(e.Dir, "log")
	for _, d := range []string{e.Spool, e.LogDir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	e.Upstream = fakeserver.New(t, fakeserver.Options{Store: e.Store})
	e.Listen = freeAddr(t)
	t.Cleanup(func() {
		if t.Failed() {
			t.Logf("upstream received %d lines:\n  %s", len(e.Upstream.Lines()),
				strings.Join(e.Upstream.Lines(), "\n  "))
		}
	})
	return e
}

// freeAddr returns a 127.0.0.1 address with a port that was free a moment ago.
func freeAddr(t *testing.T) string {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer l.Close()
	return l.Addr().String()
}

// DefaultAccessList allows inetd sessions (client name "stdin") and
// 127.0.0.0/8 to read and post without authentication.
const DefaultAccessList = `AccessList {
  Client stdin {
    allow read post
    List *
    Read *
    PostTo *
    Authentication none
  }
  Client 127.0.0.0/8 {
    allow read post
    List *
    Read *
    PostTo *
    Authentication none
  }
  Default {
    allow none
  }
}`

// accessEntry returns an AccessList with one Client entry for pattern that
// allows everything, and a Default entry that denies everything.
func accessEntry(pattern string) string {
	return `AccessList {
  Client ` + pattern + ` {
    allow read post
    List *
    Read *
    PostTo *
    Authentication none
  }
  Default {
    allow none
  }
}`
}

var confTmpl = template.Must(template.New("conf").Parse(`# generated by tests/e2e
ConfigVersion 5
ServerType standalone
Hostname newscache.test
Admin test@newscache.test
{{if .Listen}}ListenTo {{.Listen}}
{{end -}}
PidFile {{.Dir}}/newscache.pid
Username {{.User}}
Groupname {{.Group}}
NiceServer 0
NiceClient 0
NiceClean 0
SpoolDirectory {{.Spool}}
SpoolSize 102400
LogDirectory {{.LogDir}}
ClientTimeout {{.ClientTimeout}}
MaxConnections {{.MaxConnections}}
{{.AccessList}}
NewsServerList {
  Server {{.UpHost}} {{.UpPort}} {
    Read *
    PostTo *
    GroupTimeout {{.GroupTimeout}}
{{- if .ServerOptions}}
    Options {{.ServerOptions}}
{{- end}}
{{- if .ServerLines}}
{{.ServerLines}}
{{- end}}
  }
{{- if .ExtraServers}}
{{.ExtraServers}}
{{- end}}
}
{{.Extra}}
`))

// listenTo is the ListenTo value of the config, "" for none.
func listenTo(e *env) string {
	if e.NoListenTo {
		return ""
	}
	return firstNonEmpty(e.ListenTo, e.Listen)
}

// writeConf writes newscache.conf from the current settings.
func (e *env) writeConf() {
	e.t.Helper()
	u, err := user.Current()
	if err != nil {
		e.t.Fatal(err)
	}
	g, err := user.LookupGroupId(u.Gid)
	if err != nil {
		e.t.Fatal(err)
	}
	data := map[string]any{
		"Listen":         listenTo(e),
		"Dir":            e.Dir,
		"User":           u.Username,
		"Group":          g.Name,
		"Spool":          e.Spool,
		"LogDir":         e.LogDir,
		"ClientTimeout":  e.ClientTimeout,
		"MaxConnections": e.MaxConnections,
		"UpHost":         firstNonEmpty(e.ServerHost, e.Upstream.Host()),
		"UpPort":         firstNonEmpty(e.ServerPort, fmt.Sprint(e.Upstream.Port())),
		"ServerLines":    e.ServerLines,
		"ExtraServers":   e.ExtraServers,
		"GroupTimeout":   e.GroupTimeout,
		"ServerOptions":  e.ServerOptions,
		"Extra":          e.Extra,
		"AccessList":     e.AccessList,
	}
	var b strings.Builder
	if err := confTmpl.Execute(&b, data); err != nil {
		e.t.Fatal(err)
	}
	e.Conf = filepath.Join(e.Dir, "newscache.conf")
	if err := os.WriteFile(e.Conf, []byte(b.String()), 0o644); err != nil {
		e.t.Fatal(err)
	}
}

func (e *env) procOpts(args ...string) proc.Options {
	return proc.Options{
		Path: e.Bin,
		Args: append([]string{"-c", e.Conf}, args...),
		Dir:  e.Dir,
		Logs: []string{filepath.Join(e.LogDir, "newscache.log")},
	}
}

// session starts newscache in inetd mode (-i) for one client session and
// returns the strict client after reading the greeting.
func (e *env) session() *client.Conn {
	e.t.Helper()
	_, c := e.sessionProcess()
	return c
}

// sessionProcess also returns the inetd process so tests can wait for log
// flushing and other exit-time work instead of sleeping after QUIT.
func (e *env) sessionProcess() (*proc.Process, *client.Conn) {
	e.t.Helper()
	e.writeConf()
	p := proc.StartStdio(e.t, e.procOpts("-i"))
	c := client.New(e.t, p.Conn())
	if _, err := c.ReadGreeting(); err != nil {
		e.t.Fatalf("greeting: %v", err)
	}
	return p, c
}

func quitSession(t *testing.T, p *proc.Process, c *client.Conn) {
	t.Helper()
	if code, line := c.Cmd("QUIT"); code != 205 {
		t.Fatalf("QUIT: %q, want 205", line)
	}
	if err := p.Wait(); err != nil {
		t.Fatalf("session exit after QUIT: %v", err)
	}
}

// standalone starts newscache as a daemon in the foreground (-n) listening on
// e.Listen. Use dial to connect.
func (e *env) standalone() *proc.Process {
	e.t.Helper()
	e.writeConf()
	return proc.StartTCP(e.t, e.procOpts("-n"), e.Listen)
}

func (e *env) dial() *client.Conn {
	e.t.Helper()
	return client.Dial(e.t, e.Listen)
}

// addArticles adds n articles to a new group and returns their message-IDs.
// Each article carries an Xref header, as real servers send one.
func (e *env) addArticles(group string, n int) []string {
	return e.addArticlesXref(group, n, true)
}

func (e *env) addArticlesXref(group string, n int, xref bool) []string {
	e.Store.AddGroup(group, "test group "+group)
	ids := make([]string, 0, n)
	for i := 1; i <= n; i++ {
		id := fmt.Sprintf("<%s.%d@upstream.test>", strings.ReplaceAll(group, ".", "-"), i)
		h := []string{
			"From: poster@upstream.test",
			fmt.Sprintf("Subject: article %d in %s", i, group),
			"Newsgroups: " + group,
		}
		if xref {
			h = append(h, fmt.Sprintf("Xref: upstream.test %s:%d", group, i))
		}
		e.Store.AddArticle(group, fakeserver.Article{
			Number:    int64(i),
			MessageID: id,
			Headers:   h,
			Body:      []string{fmt.Sprintf("body of article %d", i), "second line", ".starts with a dot"},
		})
		ids = append(ids, id)
	}
	return ids
}

// knownBug marks a test that shows a known NewsCache bug. By default the test
// is skipped with the bug's ID; NEWSCACHE_KNOWN_BUGS=fail runs it as a normal
// failing test (use this when working on the fix).
func knownBug(t *testing.T, id, what string) {
	t.Helper()
	if os.Getenv("NEWSCACHE_KNOWN_BUGS") == "fail" {
		t.Logf("known bug %s: %s", id, what)
		return
	}
	t.Skipf("known bug %s: %s (NEWSCACHE_KNOWN_BUGS=fail to run)", id, what)
}

var logModes = struct {
	sync.Mutex
	byBin map[string]string
}{byBin: make(map[string]string)}

// logMode determines the build mode from the actual binary, independently of
// whether a particular test's log exists. -o needs no configuration file.
// Cache successful queries: some tests poll logFile every 50 milliseconds.
func logMode(bin string) (string, error) {
	logModes.Lock()
	defer logModes.Unlock()
	if mode, ok := logModes.byBin[bin]; ok {
		return mode, nil
	}
	b, err := exec.Command(bin, "-o").Output()
	if err != nil {
		return "", fmt.Errorf("cannot determine logging mode from %s -o: %w", bin, err)
	}
	for _, option := range strings.Fields(string(b)) {
		if option == "--with-syslog" {
			logModes.byBin[bin] = "syslog"
			return "syslog", nil
		}
	}
	logModes.byBin[bin] = "file"
	return "file", nil
}

func readLogFile(mode, path string) (string, bool, error) {
	if mode == "syslog" {
		return "", true, nil
	}
	if mode != "file" {
		return "", false, fmt.Errorf("invalid logging mode %q", mode)
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return "", false, fmt.Errorf("file-log build: cannot read %s: %w", path, err)
	}
	return string(b), false, nil
}

// logFile returns the NewsCache log, or skips only for a syslog build.
func (e *env) logFile() string {
	e.t.Helper()
	mode, err := logMode(e.Bin)
	if err != nil {
		e.t.Fatal(err)
	}
	log, skip, err := readLogFile(mode, filepath.Join(e.LogDir, "newscache.log"))
	if err != nil {
		e.t.Fatal(err)
	}
	if skip {
		e.t.Skip("binary built with syslog (configure --without-syslog to test logging)")
	}
	return log
}

// waitLog waits for a positive log marker from a standalone child/daemon.
// It is for file-log builds; logFile handles the syslog-build skip.
func (e *env) waitLog(marker string) string {
	e.t.Helper()
	deadline := time.Now().Add(5 * time.Second)
	var log string
	for {
		log = e.logFile()
		if strings.Contains(log, marker) {
			return log
		}
		if !time.Now().Before(deadline) {
			e.t.Fatalf("timed out waiting for %q in log:\n%s", marker, log)
		}
		time.Sleep(25 * time.Millisecond)
	}
}

// dialRaw connects without failing on a non-2xx greeting.
func (e *env) dialRaw() *client.Conn {
	e.t.Helper()
	c, err := client.TryDial(e.Listen, 0)
	if err != nil {
		e.t.Fatalf("dial %s: %v", e.Listen, err)
	}
	return c.WithTB(e.t)
}

// dialLenient connects with strict mode off, for replies that are known to
// break the wire format (bare LF), so the test can still check the code.
func (e *env) dialLenient() *client.Conn {
	e.t.Helper()
	nc, err := net.Dial("tcp", e.Listen)
	if err != nil {
		e.t.Fatalf("dial %s: %v", e.Listen, err)
	}
	c := client.New(e.t, nc)
	c.Strict = false
	if _, err := c.ReadGreeting(); err != nil {
		e.t.Fatalf("greeting: %v", err)
	}
	return c
}

func firstNonEmpty(a, b string) string {
	if a != "" {
		return a
	}
	return b
}
